-- Two databases: what arrives, and what we make of it.
CREATE DATABASE IF NOT EXISTS RAW
  COMMENT = 'Shopwave sources, as loaded: never edited';
CREATE SCHEMA IF NOT EXISTS RAW.SHOPWAVE;
DROP SCHEMA IF EXISTS RAW.PUBLIC;

CREATE DATABASE IF NOT EXISTS ANALYTICS
  COMMENT = 'Shopwave modelled: staging, marts, BI';
CREATE SCHEMA IF NOT EXISTS ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS ANALYTICS.MARTS;
CREATE SCHEMA IF NOT EXISTS ANALYTICS.BI;
DROP SCHEMA IF EXISTS ANALYTICS.PUBLIC;

SHOW SCHEMAS IN ACCOUNT
  ->> SELECT "database_name", "name" FROM $1
      WHERE "database_name" IN ('RAW', 'ANALYTICS')
      ORDER BY 1, 2;
