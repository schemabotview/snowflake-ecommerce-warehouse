-- A share: Brightline will read the campaign view where it is. Nothing
-- is copied, and nothing else in ANALYTICS is visible through it.
USE ROLE ACCOUNTADMIN;
CREATE SHARE IF NOT EXISTS SHOPWAVE_CAMPAIGNS
  COMMENT = 'Campaign performance, for Brightline';
GRANT USAGE ON DATABASE ANALYTICS TO SHARE SHOPWAVE_CAMPAIGNS;
GRANT USAGE ON SCHEMA ANALYTICS.BI TO SHARE SHOPWAVE_CAMPAIGNS;
GRANT SELECT ON VIEW ANALYTICS.BI.CAMPAIGN_STATS
  TO SHARE SHOPWAVE_CAMPAIGNS;
SHOW GRANTS TO SHARE SHOPWAVE_CAMPAIGNS
  ->> SELECT "privilege", "granted_on", "name" FROM $1;
