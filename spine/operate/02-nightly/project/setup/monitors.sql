-- A budget that stops spend. Only the account administrator may set one.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS RM_MONTHLY
  WITH CREDIT_QUOTA = 50
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE WH_LOAD SET RESOURCE_MONITOR = RM_MONTHLY;

SHOW RESOURCE MONITORS LIKE 'RM_MONTHLY'
  ->> SELECT "name", "credit_quota", "used_credits", "frequency"
      FROM $1;
SHOW WAREHOUSES LIKE 'WH_LOAD'
  ->> SELECT "name", "resource_monitor" FROM $1;
