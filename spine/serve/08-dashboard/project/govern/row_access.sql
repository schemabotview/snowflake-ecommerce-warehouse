-- Which countries each role may see: kept as DATA, so a new manager is a
-- new row, not a new policy.
CREATE TABLE IF NOT EXISTS REGION_COUNTRIES (
  ROLE_NAME VARCHAR, COUNTRY VARCHAR);
INSERT OVERWRITE INTO REGION_COUNTRIES
  VALUES ('REGION_MANAGER', 'DE'), ('REGION_MANAGER', 'AT');
CREATE ROW ACCESS POLICY IF NOT EXISTS BY_REGION AS (country VARCHAR)
  RETURNS BOOLEAN ->
  CURRENT_ROLE() IN ('TRANSFORMER', 'ANALYST')
  OR EXISTS (SELECT 1 FROM ANALYTICS.MARTS.REGION_COUNTRIES AS r
             WHERE r.role_name = CURRENT_ROLE() AND r.country = country);
