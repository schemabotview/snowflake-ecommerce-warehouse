-- A country manager: reads what an analyst reads, for their countries.
USE ROLE SECURITYADMIN;
GRANT CREATE ROW ACCESS POLICY ON SCHEMA ANALYTICS.MARTS
  TO ROLE TRANSFORMER;
CREATE ROLE IF NOT EXISTS REGION_MANAGER
  COMMENT = 'Country managers: the marts, for their own countries';
GRANT ROLE ANALYST TO ROLE REGION_MANAGER;
GRANT ROLE REGION_MANAGER TO ROLE SYSADMIN;
