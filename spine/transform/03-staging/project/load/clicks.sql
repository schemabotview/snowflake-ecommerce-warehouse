-- Click events: each JSON line into ONE column of type VARIANT.
CREATE TABLE IF NOT EXISTS CLICKS (
  V VARIANT, _FILE VARCHAR, _LOADED_AT TIMESTAMP_LTZ);
COPY INTO CLICKS FROM (
  SELECT $1, METADATA$FILENAME, CURRENT_TIMESTAMP()
  FROM @LANDING/clickstream/) FILE_FORMAT = (FORMAT_NAME = FF_JSON)
  ->> SELECT COUNT(*) AS files, SUM("rows_loaded") AS events FROM $1;
