-- Programs, not people: no password at all, only a key.
USE ROLE USERADMIN;
CREATE OR REPLACE USER SVC_LOADER
  TYPE = SERVICE
  RSA_PUBLIC_KEY = '<% loader_key %>'
  DEFAULT_ROLE = LOADER
  DEFAULT_WAREHOUSE = WH_LOAD
  COMMENT = 'Loads RAW: Course 5';
CREATE OR REPLACE USER SVC_DBT
  TYPE = SERVICE
  RSA_PUBLIC_KEY = '<% dbt_key %>'
  DEFAULT_ROLE = TRANSFORMER
  COMMENT = 'Runs dbt: Course 7';

USE ROLE SECURITYADMIN;
GRANT ROLE LOADER TO USER SVC_LOADER;
GRANT ROLE TRANSFORMER TO USER SVC_DBT;
