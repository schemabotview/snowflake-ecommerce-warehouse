-- What each role may do: least privilege, one grant at a time.
USE ROLE ACCOUNTADMIN;
ALTER WAREHOUSE WH_BI SET RESOURCE_MONITOR = RM_MONTHLY;
USE ROLE SECURITYADMIN;

-- LOADER: its warehouse; write RAW.SHOPWAVE, now and in future.
GRANT USAGE ON WAREHOUSE WH_LOAD TO ROLE LOADER;
GRANT USAGE ON DATABASE RAW TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE PIPE
  ON SCHEMA RAW.SHOPWAVE TO ROLE LOADER;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA RAW.SHOPWAVE TO ROLE LOADER;
GRANT SELECT, INSERT ON FUTURE TABLES IN SCHEMA RAW.SHOPWAVE TO ROLE LOADER;

-- TRANSFORMER: read RAW; build in ANALYTICS (its warehouse: Course 7).
GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA RAW.SHOPWAVE TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW.SHOPWAVE TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.SHOPWAVE TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.STAGING
  TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.MARTS
  TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.BI
  TO ROLE TRANSFORMER;

-- ANALYST: its warehouse; read the marts and BI, never RAW.
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE ANALYST;
GRANT USAGE ON DATABASE ANALYTICS TO ROLE ANALYST;
GRANT USAGE ON SCHEMA ANALYTICS.MARTS TO ROLE ANALYST;
GRANT USAGE ON SCHEMA ANALYTICS.BI TO ROLE ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.MARTS TO ROLE ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ANALYTICS.MARTS TO ROLE ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.BI TO ROLE ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ANALYTICS.BI TO ROLE ANALYST;
