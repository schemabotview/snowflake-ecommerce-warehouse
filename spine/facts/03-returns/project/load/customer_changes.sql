-- The shop's customer changes (moves, tiers), and a table that stands in
-- for the shop's live customers table, replicated as it was on a day.
CREATE TABLE IF NOT EXISTS CUSTOMER_CHANGES (
  CUSTOMER_ID NUMBER, CHANGED_AT TIMESTAMP_NTZ, FIELD VARCHAR,
  COUNTRY VARCHAR(2), LOYALTY_TIER VARCHAR);
COPY INTO CUSTOMER_CHANGES FROM @LANDING/customer_changes.csv
  FILE_FORMAT = (FORMAT_NAME = FF_CSV);
CREATE TABLE IF NOT EXISTS CUSTOMER_STATE (
  CUSTOMER_ID NUMBER, COUNTRY VARCHAR(2), LOYALTY_TIER VARCHAR,
  SIGNUP_DATE DATE, EMAIL VARCHAR, UPDATED_AT TIMESTAMP_NTZ);
