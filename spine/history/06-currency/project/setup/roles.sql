-- One role per team, each under SYSADMIN so the admins keep control.
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS LOADER COMMENT = 'Data team: loads RAW';
CREATE ROLE IF NOT EXISTS TRANSFORMER COMMENT = 'Analytics: builds ANALYTICS';
CREATE ROLE IF NOT EXISTS ANALYST COMMENT = 'BI and finance: read marts';

USE ROLE SECURITYADMIN;
GRANT ROLE LOADER TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE ANALYST TO ROLE SYSADMIN;

-- Ravi works as an analyst; Ana may test every role.
GRANT ROLE ANALYST TO USER RAVI;
SET me = CURRENT_USER();
GRANT ROLE LOADER TO USER IDENTIFIER($me);
GRANT ROLE TRANSFORMER TO USER IDENTIFIER($me);
GRANT ROLE ANALYST TO USER IDENTIFIER($me);

SHOW GRANTS OF ROLE ANALYST ->> SELECT "granted_to", "grantee_name" FROM $1;
