-- The same query on XS, then on S: what does size buy?
ALTER SESSION SET USE_CACHED_RESULT = FALSE;
USE WAREHOUSE WH_LOAD;
ALTER SESSION SET QUERY_TAG = 'XS';
SELECT l_returnflag, COUNT(*), SUM(l_extendedprice)
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM GROUP BY 1;
ALTER WAREHOUSE WH_LOAD SET WAREHOUSE_SIZE = SMALL;
ALTER SESSION SET QUERY_TAG = 'S';
SELECT l_returnflag, COUNT(*), SUM(l_extendedprice)
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM GROUP BY 1;
ALTER WAREHOUSE WH_LOAD SET WAREHOUSE_SIZE = XSMALL;
SELECT query_tag AS size, warehouse_size,
       total_elapsed_time AS elapsed_ms
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY_BY_SESSION())
WHERE query_tag IN ('XS', 'S') AND query_type = 'SELECT'
ORDER BY start_time;
