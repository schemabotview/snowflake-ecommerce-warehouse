-- One table as Snowflake stores it: immutable micro-partitions.
USE WAREHOUSE WH_LOAD;
CREATE TRANSIENT DATABASE IF NOT EXISTS LAB;
CREATE OR REPLACE TABLE LAB.PUBLIC.LINEITEM AS
  SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;
SELECT row_count, bytes FROM LAB.INFORMATION_SCHEMA.TABLES
WHERE table_name = 'LINEITEM';
SELECT j:total_partition_count::int AS partitions,
       j:average_depth::number(8, 2) AS depth
FROM (SELECT PARSE_JSON(SYSTEM$CLUSTERING_INFORMATION(
        'LAB.PUBLIC.LINEITEM', '(L_SHIPDATE)')) AS j);
DROP DATABASE LAB;
