-- How to read each kind of file: a contract, written once, named.
CREATE FILE FORMAT IF NOT EXISTS FF_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE;
CREATE FILE FORMAT IF NOT EXISTS FF_CSV_LATIN1
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('') ENCODING = 'ISO-8859-1';
CREATE FILE FORMAT IF NOT EXISTS FF_JSON
  TYPE = JSON STRIP_OUTER_ARRAY = FALSE;
CREATE FILE FORMAT IF NOT EXISTS FF_PARQUET
  TYPE = PARQUET;
SHOW FILE FORMATS ->> SELECT "name", "type" FROM $1 ORDER BY 1;
