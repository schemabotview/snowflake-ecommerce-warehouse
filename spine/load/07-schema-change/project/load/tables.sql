-- The shop's tables, as the shop has them, plus where each row came from.
CREATE TABLE IF NOT EXISTS ORDERS (
  ORDER_ID NUMBER, ORDER_TS TIMESTAMP_NTZ, CUSTOMER_ID NUMBER,
  COUNTRY VARCHAR(2), STATUS VARCHAR, TOTAL NUMBER(12, 2),
  _FILE VARCHAR, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
  ORDER_ID NUMBER, LINE NUMBER, PRODUCT_ID NUMBER, QTY NUMBER,
  UNIT_PRICE NUMBER(10, 2), _FILE VARCHAR, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS CUSTOMERS (
  CUSTOMER_ID NUMBER, COUNTRY VARCHAR(2), SIGNUP_DATE DATE,
  EMAIL VARCHAR, _FILE VARCHAR, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS FX_RATES (
  DATE DATE, CURRENCY VARCHAR(3), PER_EUR NUMBER(12, 4),
  _FILE VARCHAR, _LOADED_AT TIMESTAMP_LTZ);
